import os
import psycopg
from psycopg.rows import dict_row

from flask import Flask, request, jsonify, session
from flask_cors import CORS
from werkzeug.security import generate_password_hash, check_password_hash

app = Flask(__name__)

app.secret_key = os.environ.get("SECRET_KEY")

if not app.secret_key:
    raise RuntimeError("SECRET_KEY environment variable is missing")

DATABASE_URL = os.environ.get("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL environment variable is missing")

app.config.update(
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE="Lax",
    SESSION_COOKIE_SECURE=True
)

CORS(app, supports_credentials=True)


def get_db():
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        sslmode="require"
    )


def init_db():
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                balance BIGINT DEFAULT 0
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS services (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                provider_service_id TEXT,
                price_per_1000 BIGINT NOT NULL
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id),
                service_id BIGINT NOT NULL REFERENCES services(id),
                target_url TEXT NOT NULL,
                quantity INTEGER NOT NULL,
                cost BIGINT NOT NULL,
                provider_order_id TEXT,
                status TEXT DEFAULT 'Pending'
            )
        """)

@app.route("/")
def home():
    return jsonify({"message": "Silver Panel API is running!"})


@app.route("/health")
def health():
    return jsonify({"status": "ok"})


@app.route("/register", methods=["POST"])
def register():
    data = request.get_json(silent=True) or {}

    email = data.get("email", "").strip().lower()
    password = data.get("password", "")

    if not email or not password:
        return jsonify({"error": "Email and password are required"}), 400

    if len(password) < 8:
        return jsonify({"error": "Password must be at least 8 characters"}), 400

    password_hash = generate_password_hash(password)

    try:
        with get_db() as conn:
            conn.execute(
                "INSERT INTO users (email, password_hash) VALUES (%s, %s)",
                (email, password_hash)
            )

        return jsonify({"message": "Account created successfully"}), 201

    except psycopg.errors.UniqueViolation:
        return jsonify({"error": "Email already registered"}), 409


@app.route("/login", methods=["POST"])
def login():
    data = request.get_json(silent=True) or {}

    email = data.get("email", "").strip().lower()
    password = data.get("password", "")

    with get_db() as conn:
        user = conn.execute(
            "SELECT * FROM users WHERE email = %s",
            (email,)
        ).fetchone()

    if not user or not check_password_hash(user["password_hash"], password):
        return jsonify({"error": "Invalid email or password"}), 401

    session.clear()
    session["user_id"] = user["id"]

    return jsonify({"message": "Login successful"})


@app.route("/logout", methods=["POST"])
def logout():
    session.clear()
    return jsonify({"message": "Logged out successfully"})


def require_login():
    return session.get("user_id")

@app.route("/wallet")
def wallet():
    user_id = require_login()

    if not user_id:
        return jsonify({"error": "Please login first"}), 401

    with get_db() as conn:
        user = conn.execute(
            "SELECT balance FROM users WHERE id = %s",
            (user_id,)
        ).fetchone()

    if not user:
        return jsonify({"error": "User not found"}), 404

    return jsonify({"balance_kobo": user["balance"]})


@app.route("/services")
def services():
    with get_db() as conn:
        rows = conn.execute(
            "SELECT id, name, price_per_1000 FROM services ORDER BY id"
        ).fetchall()

    return jsonify([
        {
            "id": row["id"],
            "name": row["name"],
            "price_per_1000_kobo": row["price_per_1000"]
        }
        for row in rows
    ])


init_db()


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5000, debug=False)